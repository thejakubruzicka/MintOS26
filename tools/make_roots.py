#!/usr/bin/env python3
"""Build MintOS's trusted-root table from Mozilla's CA bundle.

Input:  assets/certs/cacert.pem  (curl.se/ca/cacert.pem, extracted from Mozilla's
        certdata.txt; Mozilla Public License 2.0, see docs/MOZILLA_CA_NOTICE.txt)
Output: kernel/user/crypto/roots_data.c

Each certificate's SHA-256 fingerprint is checked against the comment that
precedes it in the bundle. Only what chain validation needs is kept: the
subject Name (DER, compared byte-for-byte with an issuer Name) and the
SubjectPublicKeyInfo (DER). Run with no arguments; the output is committed.
"""
import base64
import hashlib
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "assets/certs/cacert.pem"
OUT = ROOT / "kernel/user/crypto/roots_data.c"


def tlv(buf, at):
    """Returns (tag, header_len, content_len) for the DER element at `at`."""
    tag = buf[at]
    length = buf[at + 1]
    hl = 2
    if length & 0x80:
        n = length & 0x7F
        if n == 0 or n > 4:
            raise ValueError("unsupported DER length")
        length = int.from_bytes(buf[at + 2:at + 2 + n], "big")
        hl += n
    if at + hl + length > len(buf):
        raise ValueError("DER element overruns the buffer")
    return tag, hl, length


def children(buf, at):
    tag, hl, ln = tlv(buf, at)
    i, end = at + hl, at + hl + ln
    out = []
    while i < end:
        t, h, l = tlv(buf, i)
        out.append((t, i, h + l))
        i += h + l
    return out


def parse(der):
    cert = children(der, 0)
    tbs_at = cert[0][1]
    fields = children(der, tbs_at)
    k = 1 if fields[0][0] == 0xA0 else 0     # optional [0] version
    # serialNumber, signature, issuer, validity, subject, subjectPublicKeyInfo
    subject = fields[k + 4]
    spki = fields[k + 5]
    if subject[0] != 0x30 or spki[0] != 0x30:
        raise ValueError("unexpected certificate layout")
    return der[subject[1]:subject[1] + subject[2]], der[spki[1]:spki[1] + spki[2]]


def main():
    text = SRC.read_text(encoding="utf-8")
    blocks = re.findall(r"\n([^\n]+)\n=+\n# Fingerprint \(SHA-256\): ([0-9A-F:]+)\n-----BEGIN CERTIFICATE-----\n(.*?)-----END CERTIFICATE-----",
                        text, re.S)
    if len(blocks) != text.count("BEGIN CERTIFICATE"):
        raise SystemExit("could not match every certificate with its fingerprint comment")
    roots = []
    for name, fp, b64 in blocks:
        der = base64.b64decode("".join(b64.split()))
        if hashlib.sha256(der).hexdigest().upper() != fp.replace(":", ""):
            raise SystemExit(f"fingerprint mismatch for {name}")
        subject, spki = parse(der)
        roots.append((name.strip(), subject, spki))
    lines = ["/* Generated by tools/make_roots.py from assets/certs/cacert.pem (Mozilla CA",
             " * certificate store via curl.se; Mozilla Public License 2.0, see",
             " * docs/MOZILLA_CA_NOTICE.txt). Do not edit. */",
             '#include "roots.h"', ""]
    blob = bytearray()
    entries = []
    for name, subject, spki in roots:
        entries.append((len(blob), len(subject), len(blob) + len(subject), len(spki), name))
        blob += subject + spki
    lines.append(f"static const uint8_t root_blob[{len(blob)}] = {{")
    for i in range(0, len(blob), 24):
        lines.append("    " + ",".join(f"0x{b:02x}" for b in blob[i:i + 24]) + ",")
    lines.append("};")
    lines.append(f"const MINT_TLS_ROOT mint_tls_roots[{len(entries)}] = {{")
    for so, sl, ko, kl, name in entries:
        safe = name.encode("ascii", "replace").decode().replace("\\", "/").replace('"', "'")
        lines.append(f'    {{root_blob + {so}, {sl}u, root_blob + {ko}, {kl}u, "{safe[:60]}"}},')
    lines.append("};")
    lines.append(f"const uint32_t mint_tls_root_count = {len(entries)}u;")
    OUT.write_text("\n".join(lines) + "\n")
    print(f"wrote {OUT.relative_to(ROOT)}: {len(entries)} roots, {len(blob)} bytes of names and keys")


if __name__ == "__main__":
    main()
