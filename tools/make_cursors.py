#!/usr/bin/env python3
"""Generate MintOS26's anti-aliased pointer sprites (kernel/ui/cursor_sprites.h).

Original drawings in the familiar desktop style: black shapes with a white
outline and a soft drop shadow, rendered at 4x and downsampled. Requires Pillow.
"""
from __future__ import annotations

import sys
from pathlib import Path

from PIL import Image, ImageChops, ImageDraw, ImageFilter

ROOT = Path(__file__).resolve().parents[1]
S = 4      # supersampling
BOX = 32   # sprite box (pixels at 1x)


def poly(points, ox=0.0, oy=0.0):
    return [((x + ox) * S, (y + oy) * S) for x, y in points]


def finish(black_mask: Image.Image, outline_px: float, shadow=True) -> Image.Image:
    """black_mask: L image at S scale. Returns RGBA at 1x with outline + shadow."""
    grow = int(round(outline_px * S)) * 2 + 1
    white_mask = black_mask.filter(ImageFilter.MaxFilter(grow))
    rgba = Image.new("RGBA", black_mask.size, (0, 0, 0, 0))
    if shadow:
        sh = white_mask.filter(ImageFilter.GaussianBlur(1.6 * S)).point(lambda v: int(v * 0.38))
        sh = ImageChops.offset(sh, int(0.6 * S), int(1.4 * S))
        rgba = Image.composite(Image.new("RGBA", black_mask.size, (0, 0, 0, 255)), rgba, sh)
        rgba.putalpha(sh)
    rgba = Image.composite(Image.new("RGBA", black_mask.size, (255, 255, 255, 255)), rgba, white_mask)
    rgba = Image.composite(Image.new("RGBA", black_mask.size, (12, 12, 14, 255)), rgba, black_mask)
    return rgba.resize((BOX, BOX), Image.LANCZOS)


def canvas():
    return Image.new("L", (BOX * S, BOX * S), 0)


def arrow():
    m = canvas()
    pts = [(0, 0), (0, 16.5), (3.9, 12.9), (6.6, 19.2), (9.2, 18.1), (6.6, 11.9), (11.7, 11.9)]
    ImageDraw.Draw(m).polygon(poly(pts, 2.2, 2.2), fill=255)
    return finish(m, 1.35), (2, 2)


def ibeam():
    m = canvas(); d = ImageDraw.Draw(m)
    cx = 16
    d.rectangle(((cx - 0.7) * S, 7 * S, (cx + 0.7) * S, 25 * S), fill=255)
    for y in (6.2, 24.4):
        d.rectangle(((cx - 3.6) * S, y * S, (cx - 0.7) * S, (y + 1.4) * S), fill=255)
        d.rectangle(((cx + 0.7) * S, y * S, (cx + 3.6) * S, (y + 1.4) * S), fill=255)
    return finish(m, 1.0, shadow=False), (16, 16)


def double_arrow(angle_deg: float):
    m = Image.new("L", (BOX * S * 2, BOX * S * 2), 0); d = ImageDraw.Draw(m)
    c = BOX * S
    L, head, shaft = 9.5, 4.6, 1.15
    pts = [(-L, 0), (-L + head, -head), (-L + head, -shaft), (L - head, -shaft), (L - head, -head),
           (L, 0), (L - head, head), (L - head, shaft), (-L + head, shaft), (-L + head, head)]
    d.polygon([(c + x * S, c + y * S) for x, y in pts], fill=255)
    m = m.rotate(angle_deg, resample=Image.BICUBIC, center=(c, c))
    m = m.crop((c - BOX * S // 2, c - BOX * S // 2, c + BOX * S // 2, c + BOX * S // 2))
    return finish(m, 1.25), (16, 16)


def main() -> int:
    sprites = [("arrow", arrow()), ("ibeam", ibeam()), ("resize_ew", double_arrow(0)),
               ("resize_ns", double_arrow(90)), ("resize_nwse", double_arrow(-45)),
               ("resize_nesw", double_arrow(45))]
    out = ["/* Generated by tools/make_cursors.py; do not edit. RGBA8, straight alpha. */",
           "#ifndef MINTOS26_CURSOR_SPRITES_H", "#define MINTOS26_CURSOR_SPRITES_H",
           "#include <stdint.h>", f"#define MINT_CURSOR_SPRITE_SIZE {BOX}u"]
    for name, (img, _) in sprites:
        data = img.tobytes()
        rows = [", ".join(str(b) for b in data[i:i + 32]) for i in range(0, len(data), 32)]
        out.append(f"static const uint8_t mint_cursor_{name}[{len(data)}] = {{")
        out.append(",\n".join("    " + r for r in rows))
        out.append("};")
    out.append("typedef struct { const uint8_t *rgba; uint8_t hot_x, hot_y; } MINT_CURSOR_SPRITE;")
    out.append("/* Index = MINT_CURSOR_SHAPE_* (1-based; 0 hides the pointer). */")
    out.append("static const MINT_CURSOR_SPRITE mint_cursor_sprites[] = {")
    out.append("    {0, 0, 0},")
    for name, (_, (hx, hy)) in sprites:
        out.append(f"    {{mint_cursor_{name}, {hx}, {hy}}},")
    out.append("};")
    out.append("#endif")
    (ROOT / "kernel/ui/cursor_sprites.h").write_text("\n".join(out) + "\n")
    preview = Image.new("RGBA", (BOX * len(sprites) * 3, BOX * 3), (210, 220, 230, 255))
    for i, (_, (img, _)) in enumerate(sprites):
        preview.alpha_composite(img.resize((BOX * 3, BOX * 3), Image.NEAREST), (i * BOX * 3, 0))
    if len(sys.argv) > 1:
        preview.save(sys.argv[1])
    print(f"wrote kernel/ui/cursor_sprites.h ({len(sprites)} sprites)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
