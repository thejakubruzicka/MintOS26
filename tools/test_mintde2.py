#!/usr/bin/env python3
"""Host tests for MintDE 2 (renderer, shared canvas, overlay pointer, RTC) and
source contracts for the macOS-style shell."""
import re
from pathlib import Path
import os
import subprocess
import tempfile

root = Path(__file__).resolve().parents[1]
cc = os.environ.get('HOST_CC', 'clang')
with tempfile.TemporaryDirectory(prefix='mintde2-') as tmp:
    exe = Path(tmp) / 'mintde2-test'
    subprocess.run([cc, '-std=c11', '-O1', '-Wall', '-Wextra', '-Werror', '-DMINT_RTC_HOST_TEST',
                    '-I', str(root / 'kernel/include'), '-I', str(root / 'kernel/user/include'),
                    str(root / 'tools/test_mintde2.c'),
                    str(root / 'kernel/user/mintde/gfx.c'),
                    str(root / 'kernel/user/mintde/font_data.c'),
                    str(root / 'kernel/ui/display_surface.c'),
                    str(root / 'kernel/ui/desktop_event.c'),
                    str(root / 'kernel/time/rtc.c'),
                    '-o', str(exe)], check=True)
    subprocess.run([str(exe)], check=True)

shell = (root / 'kernel/user/desktop.c').read_text()
apps = (root / 'kernel/user/mintde/apps.c').read_text()
syscall = (root / 'kernel/abi/syscall.c').read_text()
uefi = (root / 'uefi/main.c').read_text()
checks = {
    'canvas mapping borrows kernel buffers into the process as write-back, non-executable memory':
        'mint_address_space_map_shared(own, va0, canvas_pa, pages, MINT_PAGE_MAP_WRITE)' in syscall,
    'present and cursor syscalls bound their coordinates':
        'w > 16384 || h < 0 || h > 16384' in syscall and 'arg2 >= MINT_CURSOR_SHAPE_COUNT' in syscall,
    'glass panels recompose their blur margin before sampling (no feedback)':
        'expand_for_glass' in shell and '2 * SIDEBAR_BLUR' in shell and
        all(int(re.search(r'#define SIDEBAR_BLUR (\d+)', shell).group(1)) >= int(re.search(r'#define %s (\d+)' % k, shell).group(1))
            for k in ('MENU_BLUR', 'DOCK_BLUR')),
    'Shut Down / Restart still require an explicit confirmation alert':
        'paint_alert' in shell and 'run_power()' in shell and 'shell_request_power(MINT_POWER_ACTION_SHUTDOWN)' in shell,
    'Disk Utility only offers Erase for blank, unmounted disks; the kernel re-validates':
        'disk_is_erasable' in apps and 'd->mbr_signature_ok' in apps and 'mint_storage_format_blank(&request)' in apps,
    'UEFI loader accepts the larger wallpaper-carrying kernel within its 32 MiB span limit':
        '#define MINT_KERNEL_MAX_BYTES (24u*1024u*1024u)' in uefi and 'high-low>32ULL*1024*1024' in uefi,
    'Inter font license ships with the source': (root / 'docs/INTER_FONT_LICENSE.txt').is_file() and
        'SIL Open Font License' in (root / 'docs/INTER_FONT_LICENSE.txt').read_text(),
    'wallpapers and icons are generated by committed scripts (original artwork)':
        all((root / 'tools' / n).is_file() for n in ('make_wallpaper.py', 'make_icons.py', 'make_cursors.py', 'make_fonts.py')),
}
for name, ok in checks.items():
    print(('PASS: ' if ok else 'FAIL: ') + name)
if not all(checks.values()):
    raise SystemExit(1)
