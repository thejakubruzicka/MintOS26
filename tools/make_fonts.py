#!/usr/bin/env python3
"""Rasterize the Inter font (SIL OFL, assets/fonts/) into MintDE glyph tables.

Writes kernel/user/mintde/font_data.c: per face, 8-bit coverage bitmaps cropped
to each glyph's box, a 26.6 fixed-point advance and baseline-relative offsets.
Requires Pillow; the generated C file is committed so builds don't need it.
"""
from __future__ import annotations

import sys
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
FONTS = ROOT / "assets/fonts"

# (enum name, ttf, pixel size) in MINT_FONT_* order.
FACES = [
    ("CAPTION", "Inter-Regular.ttf", 11),
    ("CAPTION_BOLD", "Inter-SemiBold.ttf", 11),
    ("SMALL", "Inter-Regular.ttf", 12),
    ("BODY", "Inter-Regular.ttf", 13),
    ("BODY_MEDIUM", "Inter-Medium.ttf", 13),
    ("BODY_BOLD", "Inter-Bold.ttf", 13),
    ("HEADLINE", "Inter-SemiBold.ttf", 15),
    ("TITLE", "Inter-Bold.ttf", 20),
    ("LARGE", "Inter-Regular.ttf", 22),
    ("HUGE", "Inter-Bold.ttf", 30),
    ("DISPLAY", "Inter-Medium.ttf", 44),
]
EXTRA = "…•·⌘⇧⌥⌃⏎✓›‹←→↑↓—–−°©®™€£×÷±≠≤≥⌫⎋“”‘’"
CHARS = [chr(c) for c in range(32, 127)] + list(EXTRA)
GAMMA = 0.82  # mild stem darkening for 1x displays


def render_face(path: Path, size: int):
    font = ImageFont.truetype(str(path), size)
    ascent, descent = font.getmetrics()
    glyphs, bits = [], bytearray()
    lut = bytes(min(255, int(round(255 * ((v / 255) ** GAMMA)))) for v in range(256))
    for ch in CHARS:
        adv = int(round(font.getlength(ch) * 64))
        box = font.getbbox(ch, anchor="ls")
        x0, y0, x1, y1 = box
        w, h = max(0, x1 - x0), max(0, y1 - y0)
        off = len(bits)
        if w and h and ch != " ":
            img = Image.new("L", (w, h), 0)
            ImageDraw.Draw(img).text((-x0, -y0), ch, font=font, fill=255, anchor="ls")
            bits += img.tobytes().translate(lut)
        else:
            w = h = 0
        glyphs.append((ord(ch), adv, x0, y0, w, h, off))
    return ascent, descent, glyphs, bytes(bits)


def main() -> int:
    out = ["/* Generated by tools/make_fonts.py from Inter 4.1 (SIL Open Font License 1.1,",
           " * see docs/INTER_FONT_LICENSE.txt). Do not edit. */",
           '#include "font.h"', ""]
    table = []
    total = 0
    for name, ttf, size in FACES:
        ascent, descent, glyphs, bits = render_face(FONTS / ttf, size)
        glyphs.sort(key=lambda g: g[0])
        total += len(bits)
        sym = name.lower()
        out.append(f"static const uint8_t {sym}_bits[{max(1, len(bits))}] = {{")
        for i in range(0, len(bits), 40):
            out.append("    " + ",".join(str(b) for b in bits[i:i + 40]) + ",")
        if not bits:
            out.append("    0,")
        out.append("};")
        out.append(f"static const MINT_GLYPH {sym}_glyphs[{len(glyphs)}] = {{")
        for cp, adv, x0, y0, w, h, off in glyphs:
            out.append(f"    {{{cp}u, {adv}u, {x0}, {y0}, {w}u, {h}u, {off}u}},")
        out.append("};")
        line = ascent + descent
        table.append(f"    {{{size}u, {ascent}u, {descent}u, {line}u, {len(glyphs)}u, 0u, {sym}_glyphs, {sym}_bits}},")
    out.append("const MINT_FONT mint_fonts[MINT_FONT_COUNT] = {")
    out += table
    out.append("};")
    (ROOT / "kernel/user/mintde/font_data.c").write_text("\n".join(out) + "\n")
    print(f"wrote kernel/user/mintde/font_data.c: {len(FACES)} faces, {total} coverage bytes")
    return 0


if __name__ == "__main__":
    sys.exit(main())
